  static final Map<String, IsoCurrency> _byCode = {
    for (var c in currencies) c.code: c,
  };

  /// Retrieves currency metadata by 3-letter uppercase ISO code.
  /// Returns null if code is not an active ordinary monetary currency.
  static IsoCurrency? findByCode(String? code) {
    if (code == null) return null;
    return _byCode[code.trim().toUpperCase()];
  }

  /// Checks if a currency code is a valid, active ISO 4217 ordinary currency.
  static bool isValidCode(String? code) {
    return findByCode(code) != null;
  }

  /// Searches currencies by ISO code, currency name, or country/region label.
  static List<IsoCurrency> search(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return currencies;

    return currencies.where((c) {
      if (c.code.toLowerCase().contains(clean)) return true;
      if (c.name.toLowerCase().contains(clean)) return true;
      if (c.symbol.toLowerCase().contains(clean)) return true;
      for (var country in c.countries) {
        if (country.toLowerCase().contains(clean)) return true;
      }
      return false;
    }).toList();
  }

